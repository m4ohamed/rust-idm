/// حارس RAII لحذف ملف الكوكيز المؤقت تلقائياً عند انتهاء الاستدعاء أو الإلغاء
pub struct TempCookieGuard(pub std::path::PathBuf);

impl Drop for TempCookieGuard {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

/// إنشاء ملف كوكيز مؤقت بنسق Netscape القياسي لتقديمه لـ yt-dlp بدلاً من --add-header
pub fn create_temp_netscape_cookie_file(
    target_url: &str,
    raw_cookies: &str,
) -> std::io::Result<TempCookieGuard> {
    use std::io::Write;
    let host = url::Url::parse(target_url)
        .ok()
        .and_then(|u| u.host_str().map(|h| h.to_string()))
        .unwrap_or_else(|| "youtube.com".to_string());

    let domain = if host.starts_with('.') {
        host
    } else {
        format!(".{host}")
    };

    let temp_path = std::env::temp_dir().join(format!("rustidm_cookie_{}.txt", uuid::Uuid::new_v4()));
    let mut file = std::fs::File::create(&temp_path)?;
    writeln!(file, "# Netscape HTTP Cookie File")?;
    writeln!(file, "# Generated by RustIDM v2.0 for yt-dlp")?;

    for item in raw_cookies.split(';') {
        let item = item.trim();
        if item.is_empty() {
            continue;
        }
        if let Some((k, v)) = item.split_once('=') {
            let k = k.trim();
            let v = v.trim();
            if !k.is_empty() {
                writeln!(file, "{domain}\tTRUE\t/\tTRUE\t2147483647\t{k}\t{v}")?;
            }
        }
    }

    Ok(TempCookieGuard(temp_path))
}

impl MediaStreamEngine {
    /// جسر تكامل غير متزامن مع yt-dlp يدعم:
    /// 1. الإلغاء الفوري (kill_on_drop) لمنع العمليات اليتيمة.
    /// 2. الإيقاف المؤقت والاستئناف الحقيقي عبر تفعيل `--continue` (`-c`).
    /// 3. اختيار الجودات الحقيقية والتنسيقات (`format_id`).
    /// 4. التقاط أخطاء `stderr` المفصلة لعرض السبب الجذري عند الفشل بدلاً من رمز الخطأ المجرد.
    #[allow(clippy::too_many_arguments)]
    pub async fn download_via_ytdlp_with_format(
        url: &str,
        output_file: &Path,
        format_selector: Option<&str>,
        cookies_header: Option<&str>,
        referer: Option<&str>,
        user_agent: Option<&str>,
        pause_flag: Arc<AtomicBool>,
        cancel_flag: Arc<AtomicBool>,
    ) -> Result<()> {
        let fmt = format_selector
            .filter(|s| !s.trim().is_empty())
            .unwrap_or("bestvideo+bestaudio/best");

        loop {
            // انتظار انتهاء حالة الإيقاف المؤقت (Pause)
            while pause_flag.load(Ordering::Relaxed) {
                if cancel_flag.load(Ordering::Relaxed) {
                    return Err(anyhow!("تم إلغاء عملية yt-dlp"));
                }
                sleep(Duration::from_millis(200)).await;
            }

            if cancel_flag.load(Ordering::Relaxed) {
                return Err(anyhow!("تم إلغاء عملية yt-dlp"));
            }

            let mut cmd = TokioCommand::new("yt-dlp");
            cmd.kill_on_drop(true)
                .arg("--no-playlist")
                .arg("--no-warnings")
                .arg("-c") // استئناف التحميل عند المتابعة بعد الإيقاف المؤقت
                .arg("-f")
                .arg(fmt)
                .arg("--remote-components")
                .arg("ejs:github")
                .arg("--js-runtimes")
                .arg("node")
                .arg("--merge-output-format")
                .arg("mp4")
                .arg("-o")
                .arg(output_file)
                .stderr(Stdio::piped());

            let _cookie_guard = if let Some(cookie) = cookies_header.filter(|value| !value.trim().is_empty()) {
                if let Ok(guard) = create_temp_netscape_cookie_file(url, cookie) {
                    cmd.arg("--cookies").arg(&guard.0);
                    Some(guard)
                } else {
                    cmd.arg("--add-header").arg(format!("Cookie: {cookie}"));
                    None
                }
            } else {
                None
            };

            if let Some(ref_url) = referer.filter(|value| !value.is_empty()) {
                cmd.arg("--referer").arg(ref_url);
            }
            if let Some(ua) = user_agent.filter(|value| !value.is_empty()) {
                cmd.arg("--user-agent").arg(ua);
            }

            let mut child = cmd
                .arg(url)
                .spawn()
                .context("تعذر تشغيل yt-dlp؛ تأكد من تثبيت yt-dlp و ffmpeg في مسار النظام")?;

            // قراءة تدفق الأخطاء (stderr) في الخلفية لتقديم تشخيص دقيق عند حدوث أي خطأ
            let mut stderr_pipe = child.stderr.take();
            let stderr_buf = Arc::new(Mutex::new(String::new()));
            let stderr_buf_clone = Arc::clone(&stderr_buf);

            let stderr_drain = tokio::spawn(async move {
                if let Some(mut reader) = stderr_pipe.take() {
                    let mut temp = vec![0u8; 2048];
                    let mut accum = String::new();
                    while let Ok(n) = reader.read(&mut temp).await {
                        if n == 0 {
                            break;
                        }
                        accum.push_str(&String::from_utf8_lossy(&temp[..n]));
                        if accum.len() > 8192 {
                            let start_idx = accum.len() - 4096;
                            accum = accum[start_idx..].to_string();
                        }
                    }
                    let mut g = stderr_buf_clone.lock().await;
                    *g = accum;
                }
            });

            loop {
                if cancel_flag.load(Ordering::Relaxed) {
                    let _ = child.kill().await;
                    stderr_drain.abort();
                    return Err(anyhow!(
                        "تم إلغاء عملية yt-dlp وإنهاء العملية الفرعية بأمان"
                    ));
                }
                if pause_flag.load(Ordering::Relaxed) {
                    let _ = child.kill().await;
                    stderr_drain.abort();
                    break;
                }
                if let Some(status) = child.try_wait()? {
                    let _ = stderr_drain.await;
                    if status.success() {
                        return Ok(());
                    }
                    let captured_err = stderr_buf.lock().await.clone();
                    let err_detail = captured_err
                        .lines()
                        .rev()
                        .find(|l| l.contains("ERROR:") || l.contains("error:"))
                        .map(|s| s.trim().to_string())
                        .unwrap_or_else(|| {
                            format!("رمز خروج غير صفري: {:?}", status.code())
                        });

                    return Err(anyhow!("فشلت عملية yt-dlp: {err_detail}"));
                }
                sleep(Duration::from_millis(200)).await;
            }
        }
    }

    /// جسر تكامل غير متزامن مع yt-dlp يدعم الإلغاء الفوري (kill_on_drop) ومنع بقاء عمليات يتيمة
    pub async fn download_via_ytdlp_cancellable(
        url: &str,
        output_dir: &Path,
        cookies_header: Option<&str>,
        cancel_flag: Arc<AtomicBool>,
    ) -> Result<()> {
        let output_template = output_dir.join("%(title)s.%(ext)s");
        Self::download_via_ytdlp_with_format(
            url,
            &output_template,
            None,
            cookies_header,
            None,
            None,
            Arc::new(AtomicBool::new(false)),
            cancel_flag,
        )
        .await
    }
}

